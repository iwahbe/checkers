#!/usr/bin/env python3
"""Generates the standard library's Unicode and HTML tables (#640 d).

    python3 scripts/tables.py

rewrites the generated part of each file below, between its
`# ── Generated by scripts/tables.py` and `# ── End of generated` lines:

- stdlib/char.ck: PUNCTUATION, the ranges of general category P or S
  (CommonMark's "Unicode punctuation character"), and SPACE_SEPARATORS,
  category Zs;
- stdlib/string.ck: FOLDS, full case folding (CaseFolding.txt's C and F
  mappings, as Python's str.casefold applies them);
- stdlib/html.ck: ENTITIES, HTML5's named character references that end
  in `;` (the ones CommonMark recognizes), by name without it.

The Unicode data is Python's `unicodedata`; the version is checked, so
the tables change only when this script's UNICODE does.
"""

import html.entities
import pathlib
import sys
import unicodedata

UNICODE = "15.1.0"
ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "# ── Generated by scripts/tables.py"
END = "# ── End of generated"
SURROGATES = range(0xD800, 0xE000)


def scalars():
    return (c for c in range(0x110000) if c not in SURROGATES)


def ranges(pred):
    out = []
    for c in scalars():
        if pred(c):
            if out and out[-1][1] == c - 1:
                out[-1][1] = c
            else:
                out.append([c, c])
    return out


def char(c):
    """A Checkers string literal's text for character `c`."""
    if c == ord('"'):
        return '\\"'
    if c == ord("\\"):
        return "\\\\"
    if 0x20 <= c < 0x7F:
        return chr(c)
    return "\\u{%x}" % c


def string(s):
    return '"' + "".join(char(ord(c)) for c in s) + '"'


def rows(items, per_line, indent="    "):
    """Comma-separated items, `per_line` to a line, in brackets."""
    lines = []
    for i in range(0, len(items), per_line):
        lines.append(indent + ", ".join(items[i:i + per_line]))
    return "[\n" + ",\n".join(lines) + "]"


def table(name, doc, items, per_line):
    return "\n".join(
        ["# " + line for line in doc]
        + [f"let {name} = array.from_list {rows(items, per_line)}"]
    )


def section(tables):
    head = f"{BEGIN} from Unicode {UNICODE}: do not edit ──"
    return "\n\n".join([head] + tables + [END + " tables ──"])


def char_tables():
    punct = ranges(lambda c: unicodedata.category(chr(c))[0] in "PS")
    space = ranges(lambda c: unicodedata.category(chr(c)) == "Zs")
    hexes = lambda rs: ["(0x%X, 0x%X)" % (a, b) for a, b in rs]
    return section([
        table("PUNCTUATION",
              ["The ranges of characters of general category P (punctuation) or S",
               "(symbol), first and last, in order."], hexes(punct), 6),
        table("SPACE_SEPARATORS",
              ["The ranges of characters of general category Zs (space separator)."], hexes(space), 6),
    ])


def string_tables():
    folds = []
    for c in scalars():
        f = chr(c).casefold()
        if f != chr(c):
            folds.append("(0x%X, %s)" % (c, string(f)))
    return section([
        table("FOLDS",
              ["Each character that case folding changes, and what it becomes (full",
               "case folding: the C and F mappings of CaseFolding.txt), in order."], folds, 4),
    ])


def html_tables():
    names = sorted(n for n in html.entities.html5 if n.endswith(";"))
    items = ["(%s, %s)" % (string(n[:-1]), string(html.entities.html5[n])) for n in names]
    return section([
        table("ENTITIES",
              ["HTML5's named character references, by name (without its `;`), in",
               "order, and the characters each stands for."], items, 3),
    ])


def rewrite(path, generated):
    text = path.read_text()
    start = text.index(BEGIN)
    stop = text.index(END, start)
    stop = text.index("\n", stop) + 1
    new = text[:start] + generated + "\n" + text[stop:]
    if new != text:
        path.write_text(new)
        print("wrote", path.relative_to(ROOT))


def main():
    if unicodedata.unidata_version != UNICODE:
        sys.exit(f"this Python has Unicode {unicodedata.unidata_version}, not {UNICODE}")
    rewrite(ROOT / "stdlib/char.ck", char_tables())
    rewrite(ROOT / "stdlib/string.ck", string_tables())
    rewrite(ROOT / "stdlib/html.ck", html_tables())


if __name__ == "__main__":
    main()
