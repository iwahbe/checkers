#!/usr/bin/env python3
"""Measures the spellings Z3 gives a meaning of its own, for the solver
package's reader (smt/smtlib.ck, #399).

    python3 scripts/reserved.py [Z3 [LIBRARY …]]

asks `Z3 -in` (`z3` on PATH by default; it must be 5.3.3) about every
candidate spelling and writes, sorted, one per line:

- smt/reserved.txt: each candidate Z3 treats as anything but unknown;
- smt/reserved.ck: the same list as the reader's `RESERVED`, between its
  `# ── Generated by scripts/reserved.py` and `# ── End of generated` lines.

The candidates are the simple symbols (SMT-LIB 2.6, §3.1) found among the
words of the `z3` executable (and of the libz3 it loads, if it loads one,
and of each LIBRARY given), the words of the reader's own lists, the
symbols of SMT-LIB 2.6's theories, and `bv0`…`bv9` and `bv1234567890`
(Z3 reads `bvN` as a bit-vector literal at every N). Those that start with
`-` and a digit are left out: Z3 and the reader read them as numbers.

A candidate is reserved if one of its probes (`probes`) gives anything but
Z3's "unknown constant" or "unknown sort" error: the candidate alone;
applied to values of 11 sorts in 50 shapes (`SHAPES`); as an indexed
constant at 6 indices, and as an indexed function at those indices in 6
shapes; as a sort, an indexed sort, and a sort of one and of two
parameters. Z3 says "unknown constant" also for a built-in applied at
sorts it doesn't take, hence the many shapes. Z3 crashes on some probes of
some built-ins; a candidate that crashes it is reserved (`ask`).

So the list is as complete as those candidates and those probes, and no
more: a spelling Z3 knows that is in none of those words is not in it.
smt/reserved.txt was written by

    python3 scripts/reserved.py "$(which z3)" \
        "$(python3 -c 'import os, z3; print(os.path.dirname(z3.__file__))')/lib/libz3.so"

with the `z3-solver` 5.3.3 package installed. The test in tests/golden.rs
checks that the reader's list (`main reserved`) is this file's.
"""

import pathlib
import re
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TXT = ROOT / "smt" / "reserved.txt"
CK = ROOT / "smt" / "reserved.ck"
BEGIN = "# ── Generated by scripts/reserved.py"
END = "# ── End of generated"
VERSION = "Z3 version 5.3.3 "
SIMPLE = re.compile(rb"[A-Za-z~!@$%^&*_\-+=<>.?/][A-Za-z0-9~!@$%^&*_\-+=<>.?/]{0,39}")
# Words the reader itself treats specially (smt/smtlib.ck's `reserved`,
# `outside` and the operations it reads), so they are asked about too.
OWN = """let lambda forall exists ! _ as par match true false Int Bool Seq Array
xor distinct abs / to_real to_int declare-datatype push pop check-sat-assuming
get-model exit = not and or => ite + - * div mod < <= > >= select store seq.len
seq.nth seq.unit seq.++ seq.extract const seq.empty map is""".split()
# The symbols of SMT-LIB 2.6's theories (Core, Ints, Reals, Reals_Ints,
# ArraysEx, FixedSizeBitVectors with QF_BV's extensions, FloatingPoint,
# Strings), asked about too: some aren't words of the binaries.
THEORIES = """true false not => and or xor = distinct ite Bool Int Real - + * div mod abs
<= < >= > divisible / to_real to_int is_int Array select store BitVec concat
extract bvnot bvand bvor bvneg bvadd bvmul bvudiv bvurem bvshl bvlshr bvult
bvnand bvnor bvxor bvxnor bvcomp bvsub bvsdiv bvsrem bvsmod bvashr repeat
zero_extend sign_extend rotate_left rotate_right bvule bvugt bvuge bvslt bvsle
bvsgt bvsge RoundingMode FloatingPoint Float16 Float32 Float64 Float128
roundNearestTiesToEven roundNearestTiesToAway roundTowardPositive
roundTowardNegative roundTowardZero RNE RNA RTP RTN RTZ fp +oo -oo +zero -zero
NaN fp.abs fp.neg fp.add fp.sub fp.mul fp.div fp.fma fp.sqrt fp.rem
fp.roundToIntegral fp.min fp.max fp.leq fp.lt fp.geq fp.gt fp.eq fp.isNormal
fp.isSubnormal fp.isZero fp.isInfinite fp.isNaN fp.isNegative fp.isPositive
to_fp to_fp_unsigned fp.to_ubv fp.to_sbv fp.to_real String RegLan Int char
str.++ str.len str.< str.<= str.at str.substr str.prefixof str.suffixof
str.contains str.indexof str.replace str.replace_all str.replace_re
str.replace_re_all str.is_digit str.to_code str.from_code str.to_int
str.from_int re.none re.all re.allchar re.++ re.union re.inter re.* re.comp
re.diff re.+ re.opt re.range re.^ re.loop str.to_re str.in_re""".split()
CHUNK = 500


def words(path):
    data = pathlib.Path(path).read_bytes()
    found = set()
    for m in re.finditer(rb"[\x21-\x7e]+", data):
        for w in re.split(rb"[()\"'|;:,`{}\[\]#\\]", m.group()):
            if SIMPLE.fullmatch(w):
                found.add(w.decode())
    return found


def libz3(z3):
    out = subprocess.run(["ldd", z3], capture_output=True, text=True).stdout
    for line in out.splitlines():
        if "libz3" in line and "=>" in line:
            return line.split("=>")[1].split()[0]
    return None


# Values of each sort the probes apply candidates to.
VALUES = {
    "I": ("Int", None),
    "B": ("Bool", None),
    "R": ("Real", None),
    "S": ("String", None),
    "Q": ("(Seq Int)", None),
    "A": ("(Array Int Int)", None),
    "X": ("(_ BitVec 8)", None),
    "E": ("RegLan", None),
    "F": ("(_ FloatingPoint 8 24)", None),
    "M": ("RoundingMode", None),
    "C": ("Unicode", None),
}
# Argument sorts the probes apply each candidate at, and the indices of
# the indexed probes.
SHAPES = """- I B R S Q A X E F M C II BB RR SS QQ AA XX EE FF CC III BBB SSS QQQ XXX
BII AI AII SI SII QI QII QQI SE ES MF MFF MFFF MR MX MI IX XI IS SIS EEE RI IR""".split()
INDICES = ["1", "2", "8", "1 1", "8 24", "8 8"]
DECLS = [f"(declare-const |zz.{k}| {sort})" for k, (sort, _) in VALUES.items()]


def probes(s, k):
    out = []
    for shape in SHAPES:
        if shape == "-":
            out.append(f"(assert {s})")
        else:
            out.append(f"(assert ({s} {' '.join(f'|zz.{a}|' for a in shape)}))")
    for ix in INDICES:
        out.append(f"(assert (_ {s} {ix}))")
        for shape in ["I", "X", "R", "S", "II", "XX"]:
            out.append(f"(assert ((_ {s} {ix}) {' '.join(f'|zz.{a}|' for a in shape)}))")
        out.append(f"(declare-const |zz.{k}.{ix.replace(' ', '.')}| (_ {s} {ix}))")
    out.append(f"(declare-const |zz.{k}.s| {s})")
    out.append(f"(declare-const |zz.{k}.p1| ({s} Int))")
    out.append(f"(declare-const |zz.{k}.p2| ({s} Int Int))")
    return out


def unknown(message, s):
    """Whether `message` is Z3's error for `s` not being known (at these sorts)."""
    return bool(re.search(r"unknown constant " + re.escape(s) + r"( |\(|\"|$)", message)) or f"unknown sort '{s}'" in message


def run(z3, lines):
    """Z3's errors for `lines`, by line, and whether it got to the end."""
    p = subprocess.run([z3, "-in"], input="\n".join(lines) + '\n(echo "end of probes")\n', capture_output=True, text=True)
    errors = {}
    for m in re.finditer(r'^\(error "line (\d+) column \d+: ([^\n]*)', p.stdout, re.M):
        errors[int(m.group(1))] = m.group(2)
    return errors, "end of probes" in p.stdout


def ask(z3, cands):
    """The candidates of `cands` Z3 knows.

    Z3 crashes on some probes of some built-ins (`array-ext`, `set.union`).
    A run that doesn't reach its end is split until the candidate that
    crashed it is alone; that candidate is known (Z3 did something with it
    other than call it unknown), and the others are asked again."""
    lines = ["(set-logic ALL)"] + DECLS
    owner = {}
    for k, s in enumerate(cands):
        for p in probes(s, k):
            lines.append(p)
            owner[len(lines)] = s
    errors, finished = run(z3, lines)
    if not finished:
        if len(cands) == 1:
            return set(cands)
        half = len(cands) // 2
        return ask(z3, cands[:half]) | ask(z3, cands[half:])
    known = set()
    for line, s in owner.items():
        if line not in errors or not unknown(errors[line], s):
            known.add(s)
    return known


def main():
    z3 = sys.argv[1] if len(sys.argv) > 1 else shutil.which("z3")
    version = subprocess.run([z3, "-version"], capture_output=True, text=True).stdout
    if not version.startswith(VERSION):
        sys.exit(f"{z3} is {version.strip()!r}; this list is measured with {VERSION.strip()}")
    cands = words(z3) | set(OWN) | set(THEORIES) | {f"bv{i}" for i in range(10)} | {"bv1234567890"}
    lib = libz3(z3)
    if lib:
        cands |= words(lib)
    for extra in sys.argv[2:]:
        cands |= words(extra)
    # `-` and a digit start a number, so these are never a symbol the reader
    # reads.
    cands = sorted(c for c in cands if not re.match(r"-[0-9]", c))
    known = set()
    for i in range(0, len(cands), CHUNK):
        known |= ask(z3, cands[i : i + CHUNK])
    reserved = sorted(known)
    TXT.write_text("".join(s + "\n" for s in reserved))
    body = ",\n".join(f'    b"{s}"' for s in reserved)
    table = f"{BEGIN} from smt/reserved.txt ──\n\nlet RESERVED = array.from_list [\n{body}]\n\n{END} ──\n"
    src = CK.read_text()
    start, end = src.index(BEGIN), src.index(END)
    end = src.index("\n", end) + 1
    CK.write_text(src[:start] + table + src[end:])
    print(f"{len(cands)} candidates, {len(reserved)} reserved", file=sys.stderr)


if __name__ == "__main__":
    main()
